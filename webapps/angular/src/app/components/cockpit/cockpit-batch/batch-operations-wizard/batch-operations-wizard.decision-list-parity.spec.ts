import { describe, it, expect } from 'vitest';
import { readFileSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';

/**
 * Tests to verify that removal-time-decision and delete-decision operations
 * use IDENTICAL decision instance list rendering via static HTML analysis.
 *
 * WHAT THIS TEST GUARANTEES (Static HTML Structure):
 * ✓ Same HTML structure and Angular directives (*ngIf, *ngFor patterns)
 * ✓ Same CSS class names (col-check, col-id, instance-link, etc.)
 * ✓ Same i18n translation keys (cockpit.batchOps.deleteDecision.colEvalTime, etc.)
 * ✓ Same Angular bindings ([routerLink], [checked], (change), etc.)
 * ✓ Same component property references (selectedDecisionIds, decisionInstances, etc.)
 * ✓ Same conditional rendering logic (*ngIf patterns for empty/loading states)
 * ✓ Identical table column order and headers
 *
 * WHAT THIS TEST DOES NOT GUARANTEE (Runtime Behavior):
 * ✗ Actual rendered output in browser (CSS rendering, layout, visual appearance)
 * ✗ Runtime values of bindings (what selectedDecisionIds.size actually equals)
 * ✗ Component logic correctness (toggleDecisionInstance() implementation)
 * ✗ Event handlers firing correctly (click/change handlers)
 * ✗ Router navigation working (routerLink actual navigation)
 * ✗ Translation service producing correct text
 * ✗ Responsive behavior or dynamic CSS state changes
 *
 * RATIONALE FOR STATIC HTML TESTING:
 * Static HTML analysis is appropriate here because the requirement is PARITY -
 * ensuring two operations use identical markup. This prevents copy-paste divergence.
 * For testing actual rendering, see decision-detail.full-id-display.spec.ts which
 * uses TestBed and queries the rendered DOM.
 *
 * ALTERNATIVE APPROACH (not implemented):
 * A TestBed-based approach would render both operation modes, query the actual DOM,
 * and compare:
 * - Rendered column counts and header text (after translation)
 * - Actual href values generated by routerLink
 * - Checkbox states and event handler presence
 * - Visible text content and CSS computed styles
 * This would catch runtime issues but is slower and more complex.
 */

describe('BatchOperationsWizard - Decision List Parity (delete-decision vs removal-time-decision)', () => {
  // Resolve HTML file path relative to this test file (ES modules standard)
  const __filename = fileURLToPath(import.meta.url);
  const __dirname = dirname(__filename);
  const htmlPath = join(__dirname, 'batch-operations-wizard.html');
  const htmlContent = readFileSync(htmlPath, 'utf-8');

  function extractTableSection(operationId: string): string {
    const startPattern = `<div *ngIf="selectedOperationId === '${operationId}'"`;
    const startIndex = htmlContent.indexOf(startPattern);
    if (startIndex === -1) {
      throw new Error(`Could not find operation block for ${operationId}`);
    }

    let depth = 0;
    let i = startIndex;
    let inTag = false;
    let tagContent = '';

    while (i < htmlContent.length) {
      const char = htmlContent[i];

      if (char === '<') {
        inTag = true;
        tagContent = '<';
      } else if (char === '>' && inTag) {
        inTag = false;
        tagContent += '>';

        if (tagContent.startsWith('<div')) {
          depth++;
        } else if (tagContent === '</div>') {
          depth--;
          if (depth === 0) {
            // Found the closing div
            return htmlContent.substring(startIndex, i + 1);
          }
        }
      } else if (inTag) {
        tagContent += char;
      }

      i++;
    }

    throw new Error(`Could not find closing div for ${operationId}`);
  }

  function extractTableStructure(sectionHtml: string): { headers: string[]; classes: string[] } {
    const headersMatch = sectionHtml.match(/<thead>([\s\S]*?)<\/thead>/);
    if (!headersMatch) {
      return { headers: [], classes: [] };
    }
    const theadContent = headersMatch[1];

    const classMatches = theadContent.matchAll(/class="(col-[^"]+)"/g);
    const classes = Array.from(classMatches, m => m[1]);

    const i18nMatches = theadContent.matchAll(/\{\{\s*'([^']+)'\s*\|\s*translate\s*\}\}/g);
    const headers = Array.from(i18nMatches, m => m[1]);

    return { headers, classes };
  }

  // ============================================
  // TABLE STRUCTURE TESTS
  // ============================================

  describe('Table structure identity', () => {
    it('should have identical table structure (6 columns) for both operations', () => {
      const deleteSection = extractTableSection('delete-decision');
      const removalSection = extractTableSection('removal-time-decision');

      const deleteStructure = extractTableStructure(deleteSection);
      const removalStructure = extractTableStructure(removalSection);

      // Both should have 6 column classes (including col-check)
      expect(deleteStructure.classes.length).toBeGreaterThanOrEqual(5);
      expect(removalStructure.classes.length).toBe(deleteStructure.classes.length);

      // Column classes should match exactly
      expect(removalStructure.classes).toEqual(deleteStructure.classes);
    });

    it('should use identical CSS classes: col-check, col-id, col-definition, col-starttime, col-processinstance, col-actions', () => {
      const removalSection = extractTableSection('removal-time-decision');
      const structure = extractTableStructure(removalSection);

      // Verify all expected classes are present
      expect(structure.classes).toContain('col-check');
      expect(structure.classes).toContain('col-id');
      expect(structure.classes).toContain('col-definition');
      expect(structure.classes).toContain('col-starttime');
      expect(structure.classes).toContain('col-processinstance');
      expect(structure.classes).toContain('col-actions');
    });

    it('should use identical i18n keys for column headers', () => {
      const deleteSection = extractTableSection('delete-decision');
      const removalSection = extractTableSection('removal-time-decision');

      const deleteStructure = extractTableStructure(deleteSection);
      const removalStructure = extractTableStructure(removalSection);

      expect(removalStructure.headers).toEqual(deleteStructure.headers);

      expect(removalStructure.headers).toContain('cockpit.processes.columns.id');
      expect(removalStructure.headers).toContain('cockpit.batchOps.deleteDecision.colDecisionDef');
      expect(removalStructure.headers).toContain('cockpit.batchOps.deleteDecision.colEvalTime');
      expect(removalStructure.headers).toContain('cockpit.batchOps.deleteDecision.colProcessInstance');
      expect(removalStructure.headers).toContain('cockpit.processes.columns.actions');
    });
  });

  // ============================================
  // CELL CONTENT STRUCTURE TESTS
  // ============================================

  describe('Cell content structure identity', () => {
    it('should render ID column as clickable link with routerLink in both operations', () => {
      const deleteSection = extractTableSection('delete-decision');
      const removalSection = extractTableSection('removal-time-decision');

      const idLinkPattern = /<a \[routerLink\]="\['\/cockpit\/decision-instance',\s*di\.id\]"/;

      expect(deleteSection).toMatch(idLinkPattern);
      expect(removalSection).toMatch(idLinkPattern);

      expect(deleteSection).toContain('class="instance-link mono"');
      expect(removalSection).toContain('class="instance-link mono"');
    });

    it('should render process instance column with conditional link in both operations', () => {
      const deleteSection = extractTableSection('delete-decision');
      const removalSection = extractTableSection('removal-time-decision');
      const processLinkPattern = /<a \*ngIf="di\.processInstanceId"[\s\S]*?\[routerLink\]="\['\/cockpit\/processes\/instance',\s*di\.processInstanceId\]"/;

      expect(deleteSection).toMatch(processLinkPattern);
      expect(removalSection).toMatch(processLinkPattern);

      const dashPattern = /<span \*ngIf="!di\.processInstanceId">—<\/span>/;
      expect(deleteSection).toMatch(dashPattern);
      expect(removalSection).toMatch(dashPattern);
    });

    it('should render actions column with Eye icon button in both operations', () => {
      const deleteSection = extractTableSection('delete-decision');
      const removalSection = extractTableSection('removal-time-decision');

      const actionsPattern = /<td class="col-actions"[\s\S]*?<fa-icon \[icon\]="faEye"><\/fa-icon>/;

      expect(deleteSection).toMatch(actionsPattern);
      expect(removalSection).toMatch(actionsPattern);
    });

    it('should use variable name "di" (not "dec") in table row iteration for both operations', () => {
      const deleteSection = extractTableSection('delete-decision');
      const removalSection = extractTableSection('removal-time-decision');

      expect(deleteSection).toContain('*ngFor="let di of decisionInstances"');
      expect(removalSection).toContain('*ngFor="let di of decisionInstances"');

      expect(removalSection).not.toContain('*ngFor="let dec of decisionInstances"');
    });
  });

  // ============================================
  // SELECTION BEHAVIOR TESTS
  // ============================================

  describe('Selection behavior identity', () => {
    it('should have identical select-all checkbox structure in both operations', () => {
      const deleteSection = extractTableSection('delete-decision');
      const removalSection = extractTableSection('removal-time-decision');
      const selectAllPattern = /<div \*ngIf="mode === 'instances'" class="select-all-bar">/;
      expect(deleteSection).toMatch(selectAllPattern);
      expect(removalSection).toMatch(selectAllPattern);
      expect(deleteSection).toContain('[checked]="isAllDecisionOnPageSelected"');
      expect(removalSection).toContain('[checked]="isAllDecisionOnPageSelected"');
      expect(deleteSection).toContain('[indeterminate]="isDecisionIndeterminate"');
      expect(removalSection).toContain('[indeterminate]="isDecisionIndeterminate"');
      expect(deleteSection).toContain('(change)="toggleSelectAllDecision()"');
      expect(removalSection).toContain('(change)="toggleSelectAllDecision()"');
    });

    it('should have identical selection count structure in both operations', () => {
      const deleteSection = extractTableSection('delete-decision');
      const removalSection = extractTableSection('removal-time-decision');

      const countPattern = /<span class="selection-count"[\s\S]*?\[class\.selection-count--empty\]="selectedDecisionIds\.size === 0">/;
      expect(deleteSection).toMatch(countPattern);
      expect(removalSection).toMatch(countPattern);

      expect(deleteSection).toContain("'cockpit.batchOps.selectedCount' | translate");
      expect(removalSection).toContain("'cockpit.batchOps.selectedCount' | translate");
    });

    it('should have identical row checkbox structure in both operations', () => {
      const deleteSection = extractTableSection('delete-decision');
      const removalSection = extractTableSection('removal-time-decision');

      expect(deleteSection).toContain('class="col-check"');
      expect(removalSection).toContain('class="col-check"');
      expect(deleteSection).toContain('[checked]="isDecisionSelected(di.id)"');
      expect(removalSection).toContain('[checked]="isDecisionSelected(di.id)"');
      expect(deleteSection).toContain('(change)="toggleDecisionInstance(di.id)"');
      expect(removalSection).toContain('(change)="toggleDecisionInstance(di.id)"');
    });
  });

  // ============================================
  // EMPTY STATE TESTS
  // ============================================

  describe('Empty state message parity', () => {
    it('should have same empty state structure for both operations', () => {
      const deleteSection = extractTableSection('delete-decision');
      const removalSection = extractTableSection('removal-time-decision');
      const emptyPattern = /<div \*ngIf="!decisionInstancesLoading && decisionInstances\.length === 0" class="empty-state">/;
      expect(deleteSection).toMatch(emptyPattern);
      expect(removalSection).toMatch(emptyPattern);
    });

    it('should use operation-specific i18n keys for empty message (allowed exception)', () => {
      const deleteSection = extractTableSection('delete-decision');
      const removalSection = extractTableSection('removal-time-decision');
      expect(deleteSection).toContain('cockpit.batchOps.deleteDecision.noInstances');
      expect(removalSection).toContain('cockpit.batchOps.removalTimeDecision.noInstances');
    });
  });

  // ============================================
  // LOADING STATE TESTS
  // ============================================

  describe('Loading state identity', () => {
    it('should have identical loading state structure in both operations', () => {
      const deleteSection = extractTableSection('delete-decision');
      const removalSection = extractTableSection('removal-time-decision');
      const loadingPattern = /<div \*ngIf="decisionInstancesLoading" class="loading-state">/;
      expect(deleteSection).toMatch(loadingPattern);
      expect(removalSection).toMatch(loadingPattern);
      expect(deleteSection).toContain('[icon]="faSpinner"');
      expect(removalSection).toContain('[icon]="faSpinner"');
      expect(deleteSection).toContain("[animation]=\"'spin'\"");
      expect(removalSection).toContain("[animation]=\"'spin'\"");
    });
  });

  // ============================================
  // PAGINATION TESTS
  // ============================================

  describe('Pagination identity', () => {
    it('should have identical pagination component usage in both operations', () => {
      const deleteSection = extractTableSection('delete-decision');
      const removalSection = extractTableSection('removal-time-decision');

      expect(deleteSection).toContain('<app-pagination');
      expect(removalSection).toContain('<app-pagination');
      expect(deleteSection).toContain('[current]="decisionInstancesPage"');
      expect(removalSection).toContain('[current]="decisionInstancesPage"');
      expect(deleteSection).toContain('[size]="decisionInstancesPageSize"');
      expect(removalSection).toContain('[size]="decisionInstancesPageSize"');
      expect(deleteSection).toContain('[total]="decisionInstancesTotal"');
      expect(removalSection).toContain('[total]="decisionInstancesTotal"');
      expect(deleteSection).toContain('(pageChange)="onDecisionInstancesPageChange($event)"');
      expect(removalSection).toContain('(pageChange)="onDecisionInstancesPageChange($event)"');
    });
  });
});
